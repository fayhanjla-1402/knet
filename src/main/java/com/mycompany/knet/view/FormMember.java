    private void isiTabel(List<MemberModel> daftarMember) {
        tableModel.setRowCount(0);

        for (int i = 0; i < daftarMember.size(); i++) {
            MemberModel member = daftarMember.get(i);
            Object[] baris = new Object[4];
            baris[0] = member.getIdMember();
            baris[1] = member.getNama();
            baris[2] = member.getNoHp();
            baris[3] = member.getTanggalDaftar();
            tableModel.addRow(baris);
        }
    }

    private String ambilTeks(int baris, int kolom) {
        Object nilai = tableModel.getValueAt(baris, kolom);

        if (nilai == null) {
            return "";
        }

        return nilai.toString();
    }

    private void isiFormDariTabel(int baris) {
        try {
            idTerpilih = Integer.parseInt(ambilTeks(baris, 0));
            tfNama.setText(ambilTeks(baris, 1));
            tfNo.setText(ambilTeks(baris, 2));
            tfTgl.setText(ambilTeks(baris, 3));
            BtnUbah.setEnabled(true);
            BtnHapus.setEnabled(true);
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "ID member pada tabel tidak valid");
            kosongkanForm();
        }
    }

    private void kosongkanForm() {
        idTerpilih = 0;
        tfNama.setText("");
        tfNo.setText("");
        tfTgl.setText("");
        BtnUbah.setEnabled(false);
        BtnHapus.setEnabled(false);
        jtMember.clearSelection();
    }

    @Override
    public void valueChanged(ListSelectionEvent e) {
        if (e.getValueIsAdjusting()) {
            return;
        }

        int baris = jtMember.getSelectedRow();

        if (baris >= 0) {
            isiFormDariTabel(baris);
        }
    }


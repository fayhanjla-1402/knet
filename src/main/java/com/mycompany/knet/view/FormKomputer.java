    private Komputer inputKomputer() {
        String kode = tfKode.getText().trim();
        String tarifTeks = tfTarif.getText().trim();
        int tarifPerJam = 0;

        if (kode.equals("")) {
            JOptionPane.showMessageDialog(this, "Kode komputer wajib diisi");
            tfKode.requestFocus();
            return null;
        }

        if (tarifTeks.equals("")) {
            JOptionPane.showMessageDialog(this, "Tarif per jam wajib diisi");
            tfTarif.requestFocus();
            return null;
        }

        try {
            tarifPerJam = Integer.parseInt(tarifTeks);
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Tarif per jam harus berupa angka bulat");
            tfTarif.requestFocus();
            return null;
        }

        if (tarifPerJam <= 0) {
            JOptionPane.showMessageDialog(this, "Tarif per jam harus lebih dari 0");
            tfTarif.requestFocus();
            return null;
        }

        Komputer komputer = new Komputer();
        komputer.setNamaKomputer(kode);
        komputer.setTarifPerJam(tarifPerJam);
        return komputer;
    }

    private void simpanKomputer() {
        Komputer komputer = inputKomputer();

        if (komputer == null) {
            return;
        }

        try {
            repository.addKomputer(komputer);
            JOptionPane.showMessageDialog(this, "Data komputer berhasil disimpan");
            kosongkanForm();
            tampilKomputer();
        } catch (RuntimeException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage());
        }
    }

    private void ubahKomputer() {
        if (idTerpilih == 0) {
            JOptionPane.showMessageDialog(this, "Pilih data di tabel terlebih dahulu");
            return;
        }

        Komputer komputer = inputKomputer();

        if (komputer == null) {
            return;
        }

        komputer.setIdKomputer(idTerpilih);

        try {
            repository.updateKomputer(komputer);
            JOptionPane.showMessageDialog(this, "Data komputer berhasil diubah");
            kosongkanForm();
            tampilKomputer();
        } catch (RuntimeException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage());
        }
    }

    private void hapusKomputer() {
        if (idTerpilih == 0) {
            JOptionPane.showMessageDialog(this, "Pilih data di tabel terlebih dahulu");
            return;
        }

        int pilihan = JOptionPane.showConfirmDialog(this, "Yakin ingin menghapus data ini?", "Konfirmasi", JOptionPane.YES_NO_OPTION);

        if (pilihan != JOptionPane.YES_OPTION) {
            return;
        }

        try {
            repository.deleteKomputer(idTerpilih);
            JOptionPane.showMessageDialog(this, "Data komputer berhasil dihapus");
            kosongkanForm();
            tampilKomputer();
        } catch (RuntimeException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage());
        }
    }

    private void cariKomputer() {
        String kataKunci = tfCari.getText().trim();

        try {
            List<KomputerModel> hasilCari = repository.searchKomputer(kataKunci);
            kosongkanForm();
            isiTabel(hasilCari);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Gagal mencari data komputer: " + ex.getMessage());
        }
    }

    private void tampilKomputer() {
        try {
            List<KomputerModel> daftarKomputer = repository.getAllKomputer();
            isiTabel(daftarKomputer);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Gagal menampilkan data komputer: " + ex.getMessage());
        }
    }

    private void tampilSemuaKomputer() {
        tfCari.setText("");
        kosongkanForm();
        tampilKomputer();
    }

    private void muatUlangTabel() {
        SwingUtilities.invokeLater(new Runnable() {
            @Override
            public void run() {
                tampilKomputer();
            }
        });
    }

    private void isiTabel(List<KomputerModel> daftarKomputer) {
        tableModel.setRowCount(0);

        for (int i = 0; i < daftarKomputer.size(); i++) {
            KomputerModel komputer = daftarKomputer.get(i);
            Object[] baris = new Object[4];
            baris[0] = komputer.getIdKomputer();
            baris[1] = komputer.getNamaKomputer();
            baris[2] = komputer.getTarifPerJam();
            baris[3] = komputer.getStatus();
            tableModel.addRow(baris);
        }
    }

    private String ambilTeks(int baris, int kolom) {
        Object nilai = tableModel.getValueAt(baris, kolom);

        if (nilai == null) {
            return "";
        }

        return nilai.toString();
    }

    private void isiFormDariTabel(int baris) {
        try {
            idTerpilih = Integer.parseInt(ambilTeks(baris, 0));
            tfKode.setText(ambilTeks(baris, 1));
            tfTarif.setText(ambilTeks(baris, 2));
            BtnUbah.setEnabled(true);
            BtnHapus.setEnabled(true);
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "ID komputer pada tabel tidak valid");
            kosongkanForm();
        }
    }

    private void kosongkanForm() {
        idTerpilih = 0;
        tfKode.setText("");
        tfTarif.setText("");
        BtnUbah.setEnabled(false);
        BtnHapus.setEnabled(false);
        jtMember.clearSelection();
    }

    @Override
    public void valueChanged(ListSelectionEvent e) {
        if (e.getValueIsAdjusting()) {
            return;
        }

        int baris = jtMember.getSelectedRow();

        if (baris >= 0) {
            isiFormDariTabel(baris);
        }
    }

    @Override
    public void tableChanged(TableModelEvent e) {
        if (e.getType() != TableModelEvent.UPDATE) {
            return;
        }

        if (e.getColumn() != 3) {
            return;
        }

        int baris = e.getFirstRow();

        if (baris < 0) {
            return;
        }

        try {
            int idKomputer = Integer.parseInt(ambilTeks(baris, 0));
            String statusBaru = ambilTeks(baris, 3);
            repository.updateStatusKomputer(idKomputer, statusBaru);
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "ID komputer pada tabel tidak valid");
            muatUlangTabel();
        } catch (RuntimeException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage());
            muatUlangTabel();
        }
    }

